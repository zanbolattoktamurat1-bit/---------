export type Group = keyof typeof tasks
export type Progress = Record<string, boolean>
export const groups: Group[] = ['response','hardening','plan']
export const groupTitles = {response:'Инцидентке әрекет ету',hardening:'ОЖ қорғанысын күшейту',plan:'Қорғаныс жоспары'}
export const taskKey = (group: Group, index: number) => group + '-' + index
export const status = (done: boolean) => done ? 'Орындалды' : 'Орындалмаған'
export function metrics(progress: Progress, group?: Group) {
 const keys = (group ? [group] : groups).flatMap(item => tasks[item].map((_, index) => taskKey(item,index)))
 const count = keys.filter(key => progress[key]).length
 return { count, total: keys.length, percent: Math.round(count / keys.length * 100) }
}
